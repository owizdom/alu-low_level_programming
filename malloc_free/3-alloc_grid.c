#include "main.h"
#include <stdlib.h>

/**
 * alloc_grid - allocates a 2D grid of integers, each element set to 0
 * @width: the width of the grid
 * @height: the height of the grid
 *
 * Return: a pointer to the grid, or NULL on failure or if width or height
 * is 0 or negative
 */
int **alloc_grid(int width, int height)
{
	int **grid;
	int i;
	int j;

	if (width <= 0 || height <= 0)
		return (NULL);
	grid = malloc(sizeof(int *) * height);
	if (grid == NULL)
		return (NULL);
	i = 0;
	while (i < height)
	{
		grid[i] = malloc(sizeof(int) * width);
		if (grid[i] == NULL)
		{
			while (i >= 0)
			{
				free(grid[i]);
				i--;
			}
			free(grid);
			return (NULL);
		}
		j = 0;
		while (j < width)
		{
			grid[i][j] = 0;
			j++;
		}
		i++;
	}
	return (grid);
}
